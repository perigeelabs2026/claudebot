/**
 * The assistants' computer: one private Linux VM on the owner's Mac (Lima, Apple Virtualization), $0, no cloud.
 * ComputerHost is what the engine and the CLI use; LimaHost implements it. Nothing from the Mac is shared into the VM
 * (mounts: []), and the only way in is computerd on 127.0.0.1 with the per-install token.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
const run = promisify(execFile);

export type ComputerState = 'not_installed' | 'not_created' | 'stopped' | 'starting' | 'running' | 'error';
export interface ComputerHealth { state: ComputerState; detail: string; vm?: { cpus: number; memory_gb: number; disk_gb: number }; computerd?: { ok: boolean; now?: string; uptime_s?: number }; memory?: { used_pct: number | null; available_mb: number; total_mb: number }; disk?: { data?: { used_mb: number; total_mb: number } | null }; screens?: Array<{ n: number; streaming: boolean }>; snapshots: Array<{ id: string; at: string }>; checked_at: string }
export interface ComputerHost { status(): Promise<ComputerHealth>; up(): Promise<ComputerHealth>; down(): Promise<void>; snapshot(reason: string): Promise<{ id: string }>; reset(snapshotId?: string): Promise<ComputerHealth>; update(): Promise<ComputerHealth> }

const ROOT = path.resolve(import.meta.dirname, '..', '..', '..');
export const NAME = process.env.CLAUDEBOT_COMPUTER_NAME ?? 'claudebot-computer';
const DISK = `${NAME}-data`;
export const LIMACTL = ['/opt/homebrew/bin/limactl', '/usr/local/bin/limactl'].find((p) => fs.existsSync(p)) ?? 'limactl';
export const versions = () => JSON.parse(fs.readFileSync(path.join(ROOT, 'computer', 'versions.json'), 'utf8')) as { vm: { cpus: number; memory: string; disk: string; data_disk: string; zram_mb: number; screens: number }; image: { location: string; arch: string }; packages: string[]; ports: { computerd_guest: number; computerd_host: number; gateway_guest: number; gateway_host: number } };

/** The Lima template: pinned image and size, no host mounts, only computerd forwarded (to 127.0.0.1), provisioning embedded. */
export function limaYaml(): string {
  const v = versions(); const b64 = (f: string) => fs.readFileSync(path.join(ROOT, 'computer', f)).toString('base64');
  const files = { 'computerd.mjs': b64('computerd/server.mjs'), 'provision.sh': b64('provision.sh'), 'provision-runtime.sh': b64('provision-runtime.sh'), 'claude-acp': b64('runtime/claude-acp'), 'chromium-wayland': b64('runtime/chromium-wayland'), 'broker-bridge.mjs': b64('runtime/broker-bridge.mjs'), 'openclaw.json': b64('runtime/openclaw.json'), 'openclaw-gateway.service': b64('runtime/openclaw-gateway.service'), 'claudebot-handover': b64('runtime/claudebot-handover'), 'claude-acp-builder': b64('runtime/claude-acp-builder'), 'claude-acp-as-builder': b64('runtime/claude-acp-as-builder'), 'egress-proxy.mjs': b64('runtime/egress-proxy.mjs'), 'builder-egress.nft': b64('runtime/builder-egress.nft'), 'claudebot-egress.service': b64('runtime/claudebot-egress.service'), 'builder-live-check.sh': b64('runtime/builder-live-check.sh'), 'versions.json': b64('versions.json'), packages: Buffer.from(v.packages.join(' ')).toString('base64'), zram_mb: Buffer.from(String(v.vm.zram_mb)).toString('base64'), screens: Buffer.from(String(v.vm.screens)).toString('base64') };
  return `# Generated by ClaudeBot from computer/versions.json. Do not edit by hand.
vmType: vz
os: Linux
arch: ${v.image.arch}
images:
  - location: "${v.image.location}"
    arch: ${v.image.arch}
cpus: ${v.vm.cpus}
memory: "${v.vm.memory}"
disk: "${v.vm.disk}"
mounts: []
additionalDisks:
  - name: "${DISK}"
    format: true
    fsType: "ext4"
containerd:
  system: false
  user: false
portForwards:
  - guestIP: "127.0.0.1"
    guestPort: ${v.ports.computerd_guest}
    hostPort: ${v.ports.computerd_host}
    hostIP: "127.0.0.1"
  - guestIP: "127.0.0.1"
    guestPort: ${v.ports.gateway_guest}
    hostPort: ${v.ports.gateway_host}
    hostIP: "127.0.0.1"
  - guestIP: "127.0.0.1"
    guestPortRange: [1, 65535]
    ignore: true
  - guestIP: "0.0.0.0"
    guestIPMustBeZero: true
    guestPortRange: [1, 65535]
    ignore: true
  - guestIP: "::"
    guestPortRange: [1, 65535]
    ignore: true
  - guestPortRange: [1, 65535]
    proto: udp
    ignore: true
provision:
  - mode: system
    script: |
      #!/bin/bash
      set -eu
      mkdir -p /etc/claudebot
${Object.entries(files).map(([k, val]) => `      echo '${val}' | base64 -d > /etc/claudebot/${k}`).join('\n')}
      bash /etc/claudebot/provision.sh
      bash /etc/claudebot/provision-runtime.sh
`;
}

const useKeychain = () => process.platform === 'darwin' && !process.env.NODE_TEST_CONTEXT;   // tests never read or write the real Keychain
/** The per-install token: kept in the macOS Keychain (a 0600 file in the engine's secrets folder where there is no Keychain). Never printed. */
export class ComputerToken {
  private secretsDir: string;
  constructor(secretsDir: string) { this.secretsDir = secretsDir; }
  private file() { return path.join(this.secretsDir, 'computer.token'); }
  get(): string | null {
    if (useKeychain()) { try { return execFileSync('/usr/bin/security', ['find-generic-password', '-a', 'claudebot', '-s', `${NAME}.token`, '-w'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() || null; } catch { /* fall through */ } }
    try { return fs.readFileSync(this.file(), 'utf8').trim() || null; } catch { return null; }
  }
  ensure(): string {
    const have = this.get(); if (have) return have; const t = crypto.randomBytes(32).toString('hex');
    if (useKeychain()) { try { execFileSync('/usr/bin/security', ['add-generic-password', '-U', '-a', 'claudebot', '-s', `${NAME}.token`, '-w', t], { stdio: 'ignore' }); if (this.get() === t) return t; } catch { /* fall back */ } }
    fs.mkdirSync(this.secretsDir, { recursive: true, mode: 0o700 }); fs.writeFileSync(this.file(), t, { mode: 0o600 }); return t;
  }
}

export class LimaHost implements ComputerHost {
  private o: { home: string; secretsDir: string; exec?: (args: string[], input?: string) => Promise<string> };
  constructor(o: { home: string; secretsDir: string; exec?: (args: string[], input?: string) => Promise<string> }) { this.o = o; }
  private token = () => new ComputerToken(this.o.secretsDir);
  private snapDir() { return path.join(this.o.home, 'computer', 'snapshots'); }
  private async lima(args: string[], input?: string): Promise<string> {
    if (this.o.exec) return this.o.exec(args, input);
    if (input === undefined) return (await run(LIMACTL, args, { maxBuffer: 16 * 1024 * 1024, timeout: 30 * 60_000 })).stdout;
    return new Promise((resolve, reject) => { const c = execFile(LIMACTL, args, { maxBuffer: 16 * 1024 * 1024, timeout: 10 * 60_000 }, (e, out) => e ? reject(e) : resolve(out)); c.stdin?.end(input); });
  }
  /** Builder turns: the builder's own long-lived Claude sign-in (from `claude setup-token`), written over stdin into a 0400 file the
   *  builder owns. Never in argv, an event or a log; an empty token removes it. */
  async setBuilderToken(token: string): Promise<{ installed: boolean }> {
    const t = token.trim();
    if (t && !/^[A-Za-z0-9._~+/=-]{20,}$/.test(t)) throw new Error('that does not look like a token from claude setup-token');
    const script = t ? 'umask 377; f=$HOME/.claude-oauth-token; tmp=$f.tmp.$$; cat > "$tmp" && mv -f "$tmp" "$f"' : 'rm -f $HOME/.claude-oauth-token';
    await this.lima(['shell', NAME, '--', 'sudo', '-n', '-u', 'claudebot-builder', '-H', 'sh', '-c', script], t ? `${t}\n` : '');
    return { installed: !!t };
  }
  private dataDiskFile() { return path.join(os.homedir(), '.lima', '_disks', DISK, 'datadisk'); }

  async status(): Promise<ComputerHealth> {
    const at = new Date().toISOString(); const snapshots = this.snapshots();
    if (!this.o.exec && process.platform !== 'darwin') return { state: 'not_installed', detail: 'The private computer needs macOS with Lima', snapshots, checked_at: at };
    if (!this.o.exec && !fs.existsSync(LIMACTL) && LIMACTL !== 'limactl') return { state: 'not_installed', detail: 'Lima is not installed', snapshots, checked_at: at };
    let list: Array<{ name: string; status: string; cpus: number; memory: number; disk: number }> = [];
    try { list = (await this.lima(['list', '--json'])).split('\n').filter(Boolean).map((l) => JSON.parse(l)); } catch (e) { return { state: 'not_installed', detail: `Lima is not available (${(e as Error).message.slice(0, 80)})`, snapshots, checked_at: at }; }
    const me = list.find((x) => x.name === NAME); if (!me) return { state: 'not_created', detail: 'The computer has not been set up yet', snapshots, checked_at: at };
    const vm = { cpus: me.cpus, memory_gb: Math.round(me.memory / 2 ** 30), disk_gb: Math.round(me.disk / 2 ** 30) };
    if (me.status !== 'Running') return { state: me.status === 'Stopped' ? 'stopped' : 'error', detail: me.status === 'Stopped' ? 'The computer is stopped' : `Lima reports ${me.status}`, vm, snapshots, checked_at: at };
    const tok = this.token().get(); const port = versions().ports.computerd_host;
    try {
      const r = await fetch(`http://127.0.0.1:${port}/health`, { headers: { authorization: `Bearer ${tok ?? ''}` }, signal: AbortSignal.timeout(4000) });
      if (r.status === 401) return { state: 'error', detail: 'computerd refused this install\'s token', vm, snapshots, checked_at: at };
      const h = await r.json() as { computerd: { now: string; uptime_s: number }; memory: ComputerHealth['memory']; disk: ComputerHealth['disk']; screens: ComputerHealth['screens'] };
      return { state: 'running', detail: 'Running', vm, computerd: { ok: true, now: h.computerd.now, uptime_s: h.computerd.uptime_s }, memory: h.memory, disk: h.disk, screens: h.screens, snapshots, checked_at: at };
    } catch { return { state: 'starting', detail: 'The VM is running; computerd is not answering yet', vm, snapshots, checked_at: at }; }
  }
  async up(): Promise<ComputerHealth> {
    const tok = this.token().ensure(); const st = await this.status();
    if (st.state === 'not_installed') throw new Error('Install Lima first (brew install lima)');
    if (st.state === 'not_created') {
      const v = versions(); const disks = await this.lima(['disk', 'ls', '--json']).catch(() => '');
      if (!disks.includes(`"name":"${DISK}"`)) await this.lima(['disk', 'create', DISK, '--size', v.vm.data_disk]);
      const yaml = path.join(this.o.home, 'computer', `${NAME}.yaml`); fs.mkdirSync(path.dirname(yaml), { recursive: true }); fs.writeFileSync(yaml, limaYaml());
      await this.lima(['start', `--name=${NAME}`, '--tty=false', yaml]);
      const inst = path.join(os.homedir(), '.lima', NAME, 'lima.yaml'); try { fs.writeFileSync(inst, fs.readFileSync(inst, 'utf8').replace(/^(\s+)format: true$/m, '$1format: false')); } catch { /* the next start keeps the default */ }
    } else if (st.state !== 'running' && st.state !== 'starting') await this.lima(['start', NAME, '--tty=false']);
    await this.lima(['shell', NAME, '--', 'sudo', 'sh', '-c', 'd=$(ls -d /mnt/lima-*-data | head -1); u=$(systemctl show -p User --value computerd); install -d -m 700 "$d/computerd"; umask 077; cat > "$d/computerd/token"; chown -R "${u:-root}" "$d/computerd"; systemctl restart computerd'], tok);
    try { const gt = (await this.lima(['shell', NAME, '--', 'sh', '-c', 'cat $(ls -d /mnt/lima-*-data | head -1)/secrets/gateway.token 2>/dev/null'])).trim(); if (/^[0-9a-f]{32,}$/.test(gt)) { fs.mkdirSync(this.o.secretsDir, { recursive: true, mode: 0o700 }); fs.writeFileSync(path.join(this.o.secretsDir, 'computer-gateway.token'), gt, { mode: 0o600 }); } } catch { /* the runtime is not provisioned yet */ }
    for (let i = 0; i < 60; i++) { const s = await this.status(); if (s.state === 'running') return s; await new Promise((r) => setTimeout(r, 2000)); }
    return this.status();
  }
  async down(): Promise<void> { await this.lima(['stop', NAME]); }
  snapshots(): Array<{ id: string; at: string }> { try { return fs.readdirSync(this.snapDir()).filter((d) => /^\d{8}T\d{6}Z/.test(d)).sort().reverse().map((id) => ({ id, at: `${id.slice(0, 4)}-${id.slice(4, 6)}-${id.slice(6, 8)}T${id.slice(9, 11)}:${id.slice(11, 13)}:${id.slice(13, 15)}Z` })); } catch { return []; } }
  /** Copy-on-write clone of the data disk (APFS, instant). The VM is stopped for the moment of the copy: a clone taken while it
   *  runs (even with the filesystem frozen) did not restore reliably in testing, so a snapshot costs one short restart. Keeps 3. */
  async snapshot(reason: string): Promise<{ id: string }> {
    const id = `${new Date().toISOString().replace(/[-:]/g, '').replace(/\.\d+Z$/, 'Z')}-${reason.replace(/[^a-z0-9]+/gi, '-').slice(0, 30)}`; const dest = path.join(this.snapDir(), id);
    const st = (await this.status()).state; const running = st === 'running' || st === 'starting';
    if (running) await this.lima(['stop', NAME]);
    try { fs.mkdirSync(dest, { recursive: true }); execFileSync('/bin/cp', ['-c', this.dataDiskFile(), path.join(dest, 'datadisk')]); }
    finally { if (running) await this.up(); }
    for (const old of this.snapshots().slice(3)) fs.rmSync(path.join(this.snapDir(), old.id), { recursive: true, force: true });
    return { id };
  }
  async reset(snapshotId?: string): Promise<ComputerHealth> {
    const snap = snapshotId ? this.snapshots().find((s) => s.id === snapshotId) : this.snapshots()[0]; if (!snap) throw new Error('there is no snapshot to reset to');
    await this.lima(['stop', NAME]).catch(() => {});
    execFileSync('/bin/cp', ['-c', path.join(this.snapDir(), snap.id, 'datadisk'), this.dataDiskFile()]);
    return this.up();
  }
  /** Snapshot first, then bring packages and ClaudeBot's own services up to date (same provisioning as first boot). */
  async update(): Promise<ComputerHealth> {
    await this.snapshot('before-update');
    const v = versions(); const b64 = (f: string) => fs.readFileSync(path.join(ROOT, 'computer', f)).toString('base64');
    const ship = (f: string, as: string) => `echo '${b64(f)}' | base64 -d > /etc/claudebot/${as};`;
    const script = `set -e; mkdir -p /etc/claudebot; ${ship('computerd/server.mjs', 'computerd.mjs')} ${ship('provision.sh', 'provision.sh')} ${ship('provision-runtime.sh', 'provision-runtime.sh')} ${ship('runtime/claude-acp', 'claude-acp')} ${ship('runtime/chromium-wayland', 'chromium-wayland')} ${ship('runtime/broker-bridge.mjs', 'broker-bridge.mjs')} ${ship('runtime/openclaw.json', 'openclaw.json')} ${ship('runtime/openclaw-gateway.service', 'openclaw-gateway.service')} ${ship('runtime/claudebot-handover', 'claudebot-handover')} ${ship('runtime/claude-acp-builder', 'claude-acp-builder')} ${ship('runtime/claude-acp-as-builder', 'claude-acp-as-builder')} ${ship('runtime/egress-proxy.mjs', 'egress-proxy.mjs')} ${ship('runtime/builder-egress.nft', 'builder-egress.nft')} ${ship('runtime/claudebot-egress.service', 'claudebot-egress.service')} ${ship('runtime/builder-live-check.sh', 'builder-live-check.sh')} ${ship('versions.json', 'versions.json')} echo '${v.packages.join(' ')}' > /etc/claudebot/packages; echo ${v.vm.zram_mb} > /etc/claudebot/zram_mb; echo ${v.vm.screens} > /etc/claudebot/screens; DEBIAN_FRONTEND=noninteractive apt-get update && DEBIAN_FRONTEND=noninteractive apt-get -y upgrade && bash /etc/claudebot/provision.sh && bash /etc/claudebot/provision-runtime.sh`;
    await this.lima(['shell', NAME, '--', 'sudo', 'bash', '-s'], script);
    return this.up();
  }
}
